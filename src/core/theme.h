// ============================================================
//  theme.h — дизайн-система «Tactical HUD»: цвета, шрифты, эффекты
//
//  ЦВЕТ — у каждого цвета один смысл:
//    фон        — тёмно-синий (C_BG)
//    акцент     — бирюзовый: выбор, главное значение, активное (C_ACC)
//    значение   — почти белый: цифры и имена (C_HOT)
//    подпись    — стальной: названия полей (UI_LABEL, core/ui.h)
//    вторичное  — тусклый стальной: подсказки, оси (UI_DIM)
//    линии      — тёмный стальной: рамки, сетка (UI_LINE)
//    тревога    — оранжевый, ТОЛЬКО тревога: метки, открытые сети,
//                 низкий заряд, шумный канал (C_ALERT)
//    «жар»      — сила сигнала: стальной -> бирюзовый -> белый (heat)
//  Любой другой цвет C(r, g, b) приводится к бирюзово-стальной шкале по яркости,
//  поэтому экраны не могут случайно «покраситься» в постороннее.
//
//  ШРИФТЫ (txt size): 1 — пиксельный 6×8 для подписей (ЗАГЛАВНЫМИ),
//  2 — Share Tech Mono 14 px для текста, 4 — Rajdhani 24 px для заголовков
//  и крупных значений, 6 — Rajdhani 44 px для главного числа экрана,
//  7 — встроенный «семисегментный».
// ============================================================
#pragma once
#include <Arduino.h>

uint16_t C(uint8_t r, uint8_t g, uint8_t b);   // цвет, приведённый к палитре
uint16_t scale565(uint16_t c, int pct);         // тот же цвет тусклее (ближе к фону): pct% (100 — как есть)
uint16_t C_BG();
uint16_t C_HOT();
uint16_t C_ALERT();
uint16_t C_ACC();
uint16_t C_SEAL();                              // цвет печати 天眼 (сейчас = акцент)
uint16_t TC(uint8_t r, uint8_t g, uint8_t b);   // буквальный цвет (точка перекраски для будущих тем)

// size: 1 встроенный мелкий, 2 STM14, 4 RAJ24, 6 RAJ44, 7 «семисегментный»;
//       3 JBM14 и 5 JBM19 — с русскими буквами (UTF-8), для текстов с ноутбука/телефона
void txt(const char* s, int x, int y, int size);
void txtNum(long n, int x, int y, int size);
int  txtW(const char* s, int size);

uint16_t heatV(float x);           // x = 0..1
uint16_t heat(int rssi);           // -100 dBm (холодно) .. -40 dBm (горячо)

// Значок-буква: буква в рамке; inverted — тёмная буква на светлом (тревога).
void drawGlyph(int x, int y, char ch, uint16_t col, bool inverted);   // (x, y) — центр
static const int GLYPH_W = 9, GLYPH_H = 11;
// Отметка цели на радаре: ромб; тревога — залитый оранжевый ромб с кольцом.
void drawMarker(int x, int y, uint16_t col, bool alert);

void present();                    // уголки-скобки + вывести кадр на экран
